import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {PDFDocument} from 'pdf-lib';
import {browse, js, save, shot, until} from './browser-driver.mjs';

const pdf = await PDFDocument.create();
pdf.addPage().drawText('QA certificate attachment - isolated acceptance only');
const fixture = resolve('tmp/delivery-completion-20260908/private/acceptance.pdf');
writeFileSync(fixture, await pdf.save());
browse('goto', 'http://127.0.0.1:3120/admin/');
await until('document.querySelector("button[aria-label=图片与文件]")');
browse('click', 'button[aria-label="图片与文件"]');
browse('upload', 'input[type=file]', fixture);
await until('document.body.innerText.includes("acceptance.pdf")');
shot('cms-pdf-upload');
browse('click', 'button[aria-label="专利资质"]');
await until('Array.from(document.querySelectorAll("label")).some(el=>el.textContent.includes("PDF 附件"))');
const pdfId=js('Array.from(Array.from(document.querySelectorAll("label")).find(el=>el.textContent.includes("PDF 附件")).querySelector("select").options).find(option=>option.value).value');
browse('select', 'label:has-text("PDF 附件") select', pdfId);
browse('click', 'button:has-text("保存草稿")');
await until('document.body.innerText.includes("草稿已保存")');
browse('click', 'button:text-is("发布")');
browse('click', 'button:has-text("确认发布")');
save('cms-publish-start', {pdfId, startedAt:new Date().toISOString()});
console.log('CMS build/deploy started from the actual publish button.');
await until('document.body.innerText.includes("已发布到网站") || document.querySelector("[role=alert]")', 960000);
const error=js('document.querySelector("[role=alert]")?.textContent ?? ""');
if(error)throw new Error(error);
shot('cms-publish-success');
browse('goto','http://127.0.0.1:3120/zh/patents/');
await until('Array.from(document.querySelectorAll("a[download]")).some(a=>a.href.endsWith(".pdf"))');
const href=js('Array.from(document.querySelectorAll("a[download]")).find(a=>a.href.endsWith(".pdf")).href');
const response=await fetch(href);
if(response.status!==200)throw new Error(`Public PDF returned ${response.status}`);
const bytes=Buffer.from(await response.arrayBuffer());
if((await PDFDocument.load(bytes)).getPageCount()!==1)throw new Error('Unexpected PDF contents');
shot('published-pdf-link');
save('cms-pdf-publication',{passed:true,pdfId,publicStatus:response.status,pdfBytes:bytes.length,liveRelease:await (await fetch('http://127.0.0.1:3120/release.json')).json()});
console.log('PDF upload, bind, real static build/deploy and public PDF download passed.');
